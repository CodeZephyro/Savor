// Helper to randomly pick 6-8 fresh community uploaded recipes on each reload
export function pickFreshUploadedRecipes(count: number = 7): Recipe[] {
  const shuffled = [...RECIPE_CATALOGUE_POOL].sort(() => 0.5 - Math.random());
  const selected = shuffled.slice(0, Math.max(6, Math.min(8, count)));
  
  // Assign realistic fresh timestamps: e.g. 2 mins ago, 7 mins ago, etc.
  return selected.map((recipe, idx) => {
    const minutesAgo = (idx + 1) * 3 + Math.floor(Math.random() * 5);
    return {
      ...recipe,
      id: `${recipe.id}-fresh-${Date.now().toString().slice(-4)}-${idx}`,
      createdAt: new Date(Date.now() - minutesAgo * 60 * 1000).toISOString(),
    };
  });
}
